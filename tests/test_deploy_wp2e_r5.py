"""WP-2E R5: the attachment-proof evidence boundary.

The R4-F3 contract still parsed the LAST stdout line, so any dependency that printed a JSON
object last could be mistaken for the proof's own verdict. In particular a dependency printing
`{"verdict": "refused", "reason": "loader_mismatch"}` followed by an OperationalError was reported
as `attachment_proof` (NOT RESTORABLE) even though nothing had verified the archive.

R5 gives the proof two things it alone controls:

* a deliberate-refusal status of its own (3), distinct from the ordinary uncaught-exception status
  (1), Docker's execution statuses and a signal termination; and
* a framed record on stdout, `HH-ATTACHMENT-PROOF <per-run token> <JSON>`, where the token is
  generated by the host for this one invocation. Only a line carrying this run's token is
  evidence; every other stdout byte is dependency diagnostics.

The host additionally requires exactly one framed line, as the final non-empty line, one complete
duplicate-free JSON object, exact fields and types, an allowlisted refusal reason, and agreement
between the process status and the record. Every disagreement or malformation is
`attachment_proof_environment` (exit 4), never `attachment_proof` (NOT RESTORABLE).

These tests exercise the host consumer directly. The proof program itself (framed emission and
statuses) is driven as a real process in `tests/test_deploy_wp2e_r4.py`.
"""

from __future__ import annotations

import json
import subprocess

import pytest

from deploy.postgres import maintenance

PREFIX = maintenance._ATTACHMENT_PROOF_PREFIX
NONCE_ENV = maintenance._ATTACHMENT_PROOF_NONCE_ENV


def _frame(nonce: str, record) -> bytes:
    return (
        f"{PREFIX} {nonce} {json.dumps(record, sort_keys=True)}\n"
    ).encode("utf-8")


class _Tools:
    """Return one raw stdout/status, optionally built with the per-invocation token."""

    def __init__(self, stdout=None, *, returncode=0, build=None):
        self.stdout = stdout
        self.returncode = returncode
        self.build = build

    def run(self, program, **kwargs):
        nonce = next(
            entry.split("=", 1)[1]
            for entry in kwargs["environment"]
            if entry.startswith(NONCE_ENV + "=")
        )
        stdout = self.build(nonce) if self.build is not None else self.stdout
        return subprocess.CompletedProcess(
            program, self.returncode, stdout=stdout, stderr=b""
        )


def _proof(tools):
    return maintenance.attachment_proof(
        tools,
        app_image="house-helper:local",
        database="house_helper_restore_x",
        role="hh_restore",
        passfile_value=None,
        network="none",
        host="127.0.0.1",
        isolated_container="a" * 64,
    )


def _refused_code(tools) -> str:
    with pytest.raises(maintenance.MaintenanceError) as refused:
        _proof(tools)
    return refused.value.code


# --- the Codex findings: none of these may become NOT RESTORABLE ---------------------------


def test_a_refusal_without_a_reason_is_environment():
    assert (
        _refused_code(
            _Tools(
                build=lambda nonce: _frame(nonce, {"verdict": "refused"}),
                returncode=3,
            )
        )
        == "attachment_proof_environment"
    )


def test_a_duplicate_verdict_key_is_environment():
    def build(nonce):
        return (
            f'{PREFIX} {nonce} '
            '{"verdict": "refused", "reason": "loader_mismatch", "verdict": "refused"}\n'
        ).encode("utf-8")

    assert _refused_code(_Tools(build=build, returncode=3)) == "attachment_proof_environment"


def test_exit_zero_with_a_refusal_verdict_is_environment():
    assert (
        _refused_code(
            _Tools(
                build=lambda nonce: _frame(
                    nonce, {"verdict": "refused", "reason": "loader_mismatch"}
                ),
                returncode=0,
            )
        )
        == "attachment_proof_environment"
    )


def test_two_contradictory_records_are_environment():
    def build(nonce):
        return _frame(nonce, {"verdict": "ok", "count": 0, "bytes": 0,
                              "declared_bytes": 0, "sample": False}) + _frame(
            nonce, {"verdict": "refused", "reason": "loader_mismatch"}
        )

    assert _refused_code(_Tools(build=build)) == "attachment_proof_environment"


@pytest.mark.parametrize(
    "record",
    [
        {"verdict": "ok", "bytes": 0, "declared_bytes": 0, "sample": False},
        {"verdict": "ok", "count": 0, "bytes": 0, "declared_bytes": 0,
         "sample": False, "extra": True},
        {"verdict": "ok", "count": True, "bytes": 0, "declared_bytes": 0, "sample": False},
        {"verdict": "ok", "count": 0, "bytes": 1, "declared_bytes": 0, "sample": False},
        {"verdict": "ok", "count": 1, "bytes": 10, "declared_bytes": 10, "sample": True},
        {"verdict": "ok", "count": 1, "bytes": 10, "declared_bytes": 10, "sample": True,
         "sample_id": "", "sample_bytes": 10},
    ],
    ids=[
        "missing-count", "extra-field", "bool-count", "declared-mismatch",
        "missing-sample-fields", "empty-sample-id",
    ],
)
def test_malformed_success_proof_fields_are_environment(record):
    assert (
        _refused_code(_Tools(build=lambda nonce: _frame(nonce, record), returncode=0))
        == "attachment_proof_environment"
    )


def test_diagnostic_spoofing_followed_by_an_operational_error_is_environment():
    """The exact Codex case: a dependency's JSON-looking line is never a verdict."""
    tools = _Tools(
        stdout=b'{"verdict":"refused","reason":"loader_mismatch"}\n',
        returncode=1,
    )
    assert _refused_code(tools) == "attachment_proof_environment"


# --- strict framing and agreement -------------------------------------------------------------


def test_a_record_with_a_foreign_token_is_environment():
    assert (
        _refused_code(
            _Tools(
                build=lambda nonce: _frame("0" * 32, {"verdict": "refused",
                                                      "reason": "loader_mismatch"}),
                returncode=3,
            )
        )
        == "attachment_proof_environment"
    )


def test_an_unframed_refusal_record_is_environment_even_with_the_refusal_status():
    assert (
        _refused_code(
            _Tools(
                stdout=b'{"verdict": "refused", "reason": "loader_mismatch"}\n',
                returncode=3,
            )
        )
        == "attachment_proof_environment"
    )


def test_a_refusal_status_with_an_ok_record_is_environment():
    record = {"verdict": "ok", "count": 0, "bytes": 0, "declared_bytes": 0, "sample": False}
    assert (
        _refused_code(_Tools(build=lambda nonce: _frame(nonce, record), returncode=3))
        == "attachment_proof_environment"
    )


def test_trailing_data_after_the_record_is_environment():
    def build(nonce):
        return _frame(
            nonce, {"verdict": "ok", "count": 0, "bytes": 0, "declared_bytes": 0,
                    "sample": False}
        ) + b"unexpected trailing line\n"

    assert _refused_code(_Tools(build=build)) == "attachment_proof_environment"


def test_leading_diagnostic_output_is_ignored():
    def build(nonce):
        return (
            b'{"verdict":"refused","reason":"loader_mismatch"}\n'
            b"a dependency diagnostic line\n"
        ) + _frame(
            nonce, {"verdict": "ok", "count": 0, "bytes": 0, "declared_bytes": 0,
                    "sample": False}
        )

    assert _proof(_Tools(build=build))["verdict"] == "ok"


def test_output_that_is_not_utf8_is_environment():
    assert (
        _refused_code(_Tools(stdout=b"\xff\xfe\n", returncode=0))
        == "attachment_proof_environment"
    )


def test_a_proof_that_could_not_establish_its_result_channel_is_environment():
    """Status 4 is the program's own 'no result channel' outcome, never a Docker failure."""
    assert (
        _refused_code(_Tools(stdout=b"", returncode=4))
        == "attachment_proof_environment"
    )


@pytest.mark.parametrize(
    "reason",
    ["loader_mismatch ", "Loader_Mismatch", "unknown_reason", ""],
    ids=["trailing-space", "uppercase", "unknown", "empty"],
)
def test_a_refusal_reason_outside_the_allowlist_is_environment(reason):
    assert (
        _refused_code(
            _Tools(
                build=lambda nonce: _frame(nonce, {"verdict": "refused", "reason": reason}),
                returncode=3,
            )
        )
        == "attachment_proof_environment"
    )


# --- positive controls ------------------------------------------------------------------------


@pytest.mark.parametrize(
    "reason",
    ["byte_total_mismatch", "loader_empty", "loader_mismatch"],
)
def test_a_genuine_refusal_is_an_artifact_refusal(reason):
    with pytest.raises(maintenance.MaintenanceError) as refused:
        _proof(
            _Tools(
                build=lambda nonce: _frame(nonce, {"verdict": "refused", "reason": reason}),
                returncode=3,
            )
        )
    assert refused.value.code == "attachment_proof"
    assert refused.value.detail == reason


def test_a_complete_successful_attachment_proof_is_accepted():
    record = {
        "verdict": "ok",
        "count": 2,
        "bytes": 30,
        "declared_bytes": 30,
        "sample": True,
        "sample_id": "00000000-0000-0000-0000-000000000000",
        "sample_bytes": 10,
    }
    assert _proof(_Tools(build=lambda nonce: _frame(nonce, record))) == record


def test_an_empty_attachment_proof_is_accepted():
    record = {"verdict": "ok", "count": 0, "bytes": 0, "declared_bytes": 0, "sample": False}
    assert _proof(_Tools(build=lambda nonce: _frame(nonce, record))) == record
