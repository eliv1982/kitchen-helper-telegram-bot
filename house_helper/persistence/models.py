"""The persistent data model.

Ownership: every user-owned row reaches its owner through a foreign key chain
that ends at users.id (allowlist_entries, identity_links, sessions,
conversations -> messages and turn_requests). Deleting a user deletes everything
beneath them. The owner of a request is always taken from the server-side
Session, never from client input; nothing here accepts or trusts a user id from
outside. A turn request has no user column of its own: its owner is its
conversation's, so there is no second copy that could disagree.

Cascades belong to the database: every owned-by foreign key is ON DELETE CASCADE,
and every one-to-many relationship that owns rows is passive_deletes="all" with
only save-update and merge cascades (SQLAlchemy does not allow "all" together
with a delete cascade), so the ORM never deletes children itself, loaded or not. That matters because a
turn request's links to messages refuse the deletion of a message that is still
linked: an ORM that deleted loaded messages one by one, in an order of its own,
would trip over them. Objects that were loaded before their owner was deleted
stay in the session until it is expired.

Referential integrity, enforced by the database and not merely by the code that
usually writes the rows: a turn request's user message and assistant message are
foreign keys that include the request's own conversation_id and the expected
role, so the message must be in the same conversation (hence of the same user)
and must have the right role. See TurnRequest.

Identity: a user is provisioned by an operator before they can sign in (onboarding
is closed). Each way that user may sign in (a Telegram OIDC subject, a verified
email) is an allowlist entry owned by that user; an identity link can exist only
for an allowlist entry of the same user. Nothing is ever linked by a name or a
claim that is not already on the list. A Telegram identity reaches the list in one
way: a verified sign-in that presents an IdentityInvitation issued for the user.

Session provenance: a session records the identity link it was opened through
(sessions.identity_link_id), and the database ties it to a link of the session's
own user (composite foreign key). A session is therefore authorized by exactly
that identity's allowlist entry, never by some other way the user may sign in,
and the identity can be revoked together with the sessions it opened (see
allowlist.revoke). See Session.

Identifiers: UUIDs generated by the server for entities that appear in URLs or
guard access (users, sessions, conversations, turn requests, ...); a database
sequence for messages, whose order within a conversation is the order of their
ids. Timestamps are timezone-aware UTC (see base.UtcDateTime).

Secrets: a session token, an emailed sign-in token, a Telegram invitation secret
or an OIDC state value is stored only as its SHA-256 hex digest, so a copy of the
database cannot be replayed. The PKCE code
verifier and nonce of an OIDC login must be sent back to the provider, so they
are stored as given, and live only until the login's expires_at.

Retention: a message, and the turn request that holds a copy of its text in
result_payload, expire at most RETENTION_DAYS (365) after their own creation.
expires_at is stored, not computed, so a later change of policy cannot silently
move the deadline of existing rows; a purge job (a later increment) deletes by
it. The 365-day ceiling is a CHECK on both tables (sqlchecks.WithinRetention)
and is checked again, with a clearer error, before an ORM insert or update. On
SQLite, where a timestamp is text, the same CHECK also requires created_at and
expires_at to be the canonical UTC spelling, "YYYY-MM-DD HH:MM:SS.ffffff" (see
base.UtcDateTime and sqlchecks.py): text with an offset, a "Z" or another
precision would compare wrongly against the bound, so it is refused.

What a person keeps: a favorite (FavoriteRecipe) and a saved shopping list
(ShoppingList) are copies with no deadline and no foreign key to the history they
came from, so they outlive the expiry, the purge and the deletion of their source.
A shopping list's creation key lives on after the list itself is gone: the
ShoppingListRequest ledger keeps each consumed (user, key) reserved for the
account's lifetime, so a lost reply can never recreate a deleted list. The purge
names the tables it deletes from and does not know any of these; only deleting the
user (the foreign key) or the person's own DELETE removes them.

Widths: SQLite does not enforce the declared width of a VARCHAR, so every
bounded text column has a matching length() CHECK, and the identifiers that come
from outside (idempotency keys, subjects) also have a character-set CHECK, which
on SQLite also requires the TEXT storage class (a BLOB with the same bytes is a
different value to a UNIQUE constraint, and its NUL bytes hide from length() and
GLOB). The application-side rules are in identifiers.py; tests run one list of
values through both.

The class named Session is the login session. It does not clash with
sqlalchemy.orm.Session as long as the two are not imported under one name.
"""

