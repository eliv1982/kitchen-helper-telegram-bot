class AllowlistEntry(Base):
    """One way a provisioned user may sign in (onboarding is closed).

    The product has one initial user and two ways in: Telegram OIDC (primary)
    and a verified email (backup). The user is created first, and each way in is
    an entry that belongs to them (user_id), so that whichever login succeeds
    resolves to the same user without ever matching on a name or an unverified
    claim.

    (provider, subject) names the identity the way its IdentityLink will once
    the person has signed in: for TELEGRAM the stable `sub` of Telegram's OIDC
    ID token (never a username, which can change hands), for EMAIL the verified
    address, lower-case (see identifiers.normalize_identity). The pair is unique
    across all users, revoked rows included: an identity belongs to exactly one
    user, and a revoked entry stays as a row with revoked_at set and is lifted
    by clearing it, so there is never a second row to disagree with the first.
    Access is granted only by an entry that exists, has revoked_at NULL and whose
    user is not disabled (allowlist.allowed_user), so anything unknown,
    malformed, revoked or disabled is refused.

    The CHECKs are the database's own copy of the rules in identifiers.py, for
    rows that did not come through it. The Unicode-aware parts of the old rule
    are gone on purpose: the subject is printable ASCII (identifiers.py says
    why).
    """

    __tablename__ = "allowlist_entries"
    __table_args__ = (
        sa.UniqueConstraint("provider", "subject"),
        # Not a second rule: the target of identity_links' composite foreign key,
        # which is what ties a link to an entry of the same user.
        sa.UniqueConstraint("user_id", "provider", "subject"),
        sa.Index(None, "user_id"),
        *_identity_checks(),
        _max_length("note", 500),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(sa.ForeignKey("users.id", ondelete="CASCADE"))
    provider: Mapped[str] = mapped_column(sa.String(64))
    subject: Mapped[str] = mapped_column(sa.String(MAX_SUBJECT_LENGTH))
    note: Mapped[Optional[str]] = mapped_column(sa.String(500))
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    revoked_at: Mapped[Optional[datetime]]

    user: Mapped[User] = relationship(back_populates="allowlist_entries")


class IdentityLink(Base):
    """Ties an identity at an external provider to a user.

    (provider, subject) follows exactly the rules of AllowlistEntry (same CHECKs)
    and is the provider's own stable id for the person: for TELEGRAM the OIDC
    `sub`, for EMAIL the verified, normalized address. It is unique: one external
    identity belongs to exactly one user.

    The composite foreign key to allowlist_entries is the account-linking rule:
    a link can only exist for an identity that was provisioned in advance, for
    the very user the link names. A sign-in with an unlisted identity, or with an
    identity listed for someone else, cannot create a link, whatever the
    application code does. Deleting the entry deletes the link (revoking, the
    normal way to take access away, keeps both).

    email is a snapshot of the claim at the last sign-in, for display only;
    access is decided by the allowlist.
    """

    __tablename__ = "identity_links"
    __table_args__ = (
        sa.UniqueConstraint("provider", "subject"),
        # Not a second rule (id alone is the key): the target of sessions' composite
        # foreign key, which is what ties a session to a link of the same user. A
        # unique index and not a UniqueConstraint (as on allowlist_entries and
        # messages), because it was added to a table that already existed: SQLite
        # cannot add a constraint in place, only by rebuilding the table, whereas a
        # unique index is a valid foreign key target on SQLite and on PostgreSQL
        # alike and needs no rebuild (see migration 0002).
        sa.Index("uq_identity_links_user_id_id", "user_id", "id", unique=True),
        sa.Index(None, "user_id"),
        # An explicit name: the convention's would be 87 characters, past
        # PostgreSQL's 63.
        sa.ForeignKeyConstraint(
            ["user_id", "provider", "subject"],
            ["allowlist_entries.user_id", "allowlist_entries.provider", "allowlist_entries.subject"],
            name="fk_identity_links_allowlist_entry",
            ondelete="CASCADE",
        ),
        *_identity_checks(),
        sa.CheckConstraint(PrintableAscii("email"), name="email_printable_ascii"),
        _max_length("email", MAX_EMAIL_LENGTH),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(sa.ForeignKey("users.id", ondelete="CASCADE"))
    provider: Mapped[str] = mapped_column(sa.String(64))
    subject: Mapped[str] = mapped_column(sa.String(MAX_SUBJECT_LENGTH))
    email: Mapped[Optional[str]] = mapped_column(sa.String(MAX_EMAIL_LENGTH))
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    last_login_at: Mapped[Optional[datetime]]

    user: Mapped[User] = relationship(back_populates="identity_links")


class Session(Base):
    """A login session. The cookie holds the token; only its SHA-256 hex digest
    (token_hash) is stored. A session is live while revoked_at is NULL and
    expires_at is in the future, its user is not disabled, and the identity it
    was opened through is still allowed (authn.authenticate).

    Provenance: identity_link_id is the link of the identity that was verified
    when the session was opened. The composite foreign key
    (user_id, identity_link_id) -> identity_links (user_id, id) makes the database
    refuse a link of another user, whatever the application code does; it is ON
    DELETE CASCADE, so deleting the link (or the allowlist entry beneath it)
    deletes the sessions it opened.

    The column is nullable for one reason: sessions that existed before the column
    did have no provenance, and it is never guessed (migration 0002 revokes them).
    The CHECK provenance_or_revoked is what keeps that from being a hole: a row
    without provenance is legal only while it is revoked, so it can never be live,
    and "un-revoking" it is refused. authn.complete_login always sets the link.

    Once stored the link does not change: the ORM refuses to rewrite it, so a
    revoked or legacy session cannot be given a provenance later. (The database
    cannot say "never updated" without a trigger; raw SQL that rewrites the column
    to another link of the same user is not prevented. Such a statement is outside
    what this module supports.)
    """

    __tablename__ = "sessions"
    __table_args__ = (
        sa.UniqueConstraint("token_hash"),
        sa.Index(None, "user_id"),
        sa.Index(None, "identity_link_id"),
        sa.Index(None, "expires_at"),
        # An explicit name: the convention's would be 51 characters; this one says
        # what the key is for.
        sa.ForeignKeyConstraint(
            ["user_id", "identity_link_id"],
            ["identity_links.user_id", "identity_links.id"],
            name="fk_sessions_identity_link",
            ondelete="CASCADE",
        ),
        sa.CheckConstraint("length(token_hash) = 64", name="token_hash_length"),
        sa.CheckConstraint("expires_at > created_at", name="expires_after_created"),
        sa.CheckConstraint(
            "identity_link_id IS NOT NULL OR revoked_at IS NOT NULL", name="provenance_or_revoked"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(sa.ForeignKey("users.id", ondelete="CASCADE"))
    identity_link_id: Mapped[Optional[uuid.UUID]]
    token_hash: Mapped[str] = mapped_column(sa.String(64))
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    last_seen_at: Mapped[datetime] = mapped_column(default=utcnow)
    expires_at: Mapped[datetime]
    revoked_at: Mapped[Optional[datetime]]

    user: Mapped[User] = relationship(back_populates="sessions")


