#
# The CHECKs above are what holds for any writer. These run first on rows written
# through the ORM, so a caller gets a ValueError that says what is wrong rather
# than a database error (and so a rule that the database cannot express, such as
# "created_at never changes", is still kept on this path). Core statements and
# raw SQL skip them and meet the CHECKs.


def check_retention(created_at: datetime, expires_at: datetime) -> None:
    """ValueError unless created_at < expires_at <= created_at + RETENTION."""
    if created_at.tzinfo is None or expires_at.tzinfo is None:
        return  # UtcDateTime refuses a naive timestamp, with its own message
    if expires_at <= created_at:
        raise ValueError("expires_at must be after created_at")
    if expires_at - created_at > MESSAGE_RETENTION:
        raise ValueError(f"expires_at may be at most {MESSAGE_RETENTION_DAYS} days after created_at")


def _changed(target: Any, *attributes: str) -> list[str]:
    state = sa.inspect(target)
    return [name for name in attributes if state.attrs[name].history.has_changes()]


def _forbid_changes(target: Any, *attributes: str) -> None:
    changed = _changed(target, *attributes)
    if changed:
        raise ValueError(f"{type(target).__name__}.{', '.join(changed)} cannot change once stored")


def _guard_retention_on_insert(mapper: Any, connection: Any, target: Any) -> None:
    if target.created_at is None:
        target.created_at = utcnow()
    if target.expires_at is None:
        target.expires_at = target.created_at + MESSAGE_RETENTION
    check_retention(target.created_at, target.expires_at)


def _guard_retention_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "created_at")
    if _changed(target, "expires_at"):
        check_retention(target.created_at, target.expires_at)


def _guard_message(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "conversation_id", "role")
    _guard_retention_on_update(mapper, connection, target)


def _guard_turn_request_on_insert(mapper: Any, connection: Any, target: Any) -> None:
    validate_idempotency_key(target.idempotency_key)
    _guard_retention_on_insert(mapper, connection, target)


def _guard_turn_request_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(
        target,
        "conversation_id",
        "idempotency_key",
        "request_fingerprint",
        "user_message_id",
    )
    _guard_retention_on_update(mapper, connection, target)


def _guard_identity(mapper: Any, connection: Any, target: Any) -> None:
    pair = (target.provider, target.subject)
    if None in pair:
        return  # NOT NULL is the database's to report
    if normalize_identity(*pair) != pair:
        raise ValueError(
            f"{type(target).__name__} {pair!r} is not in normalized form; "
            "use identifiers.normalize_identity"
        )


def _guard_session_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "identity_link_id")


def _guard_challenge_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(
        target, "user_id", "provider", "subject", "token_hash", "created_at", "expires_at"
    )


def _guard_invitation_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "user_id", "provider", "token_hash", "created_at", "expires_at")


def _guard_oidc_state_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "invitation_id")


def _guard_attachment_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "user_id", "content_type", "size_bytes", "sha256", "data", "created_at")


def _guard_telegram_link_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "user_id", "telegram_user_id", "created_at")


def _guard_telegram_code_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "user_id", "code_hash", "created_at", "expires_at")


def _guard_update_admission_on_update(mapper: Any, connection: Any, target: Any) -> None:
    """A marker records what happened; it is deleted when it expires, never rewritten."""
    _forbid_changes(
        target, "bot_id", "update_id", "kind", "admitted_at", "expires_at"
    )


def _guard_favorite_on_update(mapper: Any, connection: Any, target: Any) -> None:
    """A favorite's identity, kind and creation time never change. What it holds may
    (favorites.update_favorite): that is the edit the version guards."""
    _forbid_changes(
        target, "user_id", "source_message_id", "source_recipe_index", "kind", "created_at"
    )


def _guard_message_recipe_on_update(mapper: Any, connection: Any, target: Any) -> None:
    """A stored recipe is a record of what the answer said; it is replaced, never edited."""
    _forbid_changes(target, "message_id", "message_role", "position", "created_at")


def _guard_shopping_list_on_update(mapper: Any, connection: Any, target: Any) -> None:
    """A list's snapshot identity never changes. What it records may: its status (the
    application's complete/reopen path) and its activity time. The items are other rows."""
    _forbid_changes(
        target,
        "user_id",
        "title",
        "source_kind",
        "source_message_id",
        "source_recipe_index",
        "source_favorite_id",
        "source_favorite_version",
        "idempotency_key",
        "request_fingerprint",
        "created_at",
    )


def _guard_shopping_list_item_on_update(mapper: Any, connection: Any, target: Any) -> None:
    """An item keeps its place and its list; a person may change its name, amount and
    state, and every write moves updated_at."""
    _forbid_changes(target, "list_id", "position", "created_at")


def _guard_shopping_list_request_on_update(mapper: Any, connection: Any, target: Any) -> None:
    """A consumed key is never rewritten by the application. The one transition a row
    ever makes is the database's own SET NULL when its list is deleted."""
    _forbid_changes(
        target,
        "user_id",
        "idempotency_key",
        "request_fingerprint",
        "list_id",
        "created_at",
    )


