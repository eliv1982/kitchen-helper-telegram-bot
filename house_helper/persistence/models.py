class Message(Base):
    """One entry in a conversation's history, ordered by id (a sequence, never
    reused). A system_note is part of that order: it marks where the context
    was reset, and it expires like any other message.

    Messages are append-only by convention: a turn request's recoverable input
    is the text of its user message (see TurnRequest), so nothing may rewrite
    it. created_at, conversation_id and role never change (conversation_id and
    role are also pinned by the turn requests' foreign keys); the retention
    clock runs from created_at and expires_at is at most RETENTION_DAYS later.

    Limit: a CHECK sees one row at a time and the schema uses no triggers, so
    the database bounds the pair (created_at, expires_at) but cannot stop both
    from being moved forward together. That created_at never changes is kept on
    the ORM path only (tests/test_persistence_retention.py shows both halves).
    """

    __tablename__ = "messages"
    __table_args__ = (
        sa.Index(None, "conversation_id", "id"),
        sa.Index(None, "expires_at"),
        # Redundant as a uniqueness rule (id alone is the key); it exists to be
        # the target of turn_requests' composite foreign keys, which pin the
        # conversation and the role of the message they point at.
        sa.UniqueConstraint("conversation_id", "id", "role"),
        # The target of message_recipes' composite foreign key: it pins the role of
        # the message a structured recipe belongs to (an assistant message only). A
        # unique index, not a UniqueConstraint: SQLite cannot add a constraint in
        # place, and a unique index is a valid foreign key target on SQLite and on
        # PostgreSQL alike (the same choice as identity_links' (user_id, id), 0002).
        sa.Index("uq_messages_id_role", "id", "role", unique=True),
        sa.CheckConstraint(_in_list("role", MessageRole), name="role_valid"),
        sa.CheckConstraint("expires_at > created_at", name="expires_after_created"),
        sa.CheckConstraint(WithinRetention("created_at", "expires_at"), name="expires_within_retention"),
        # AUTOINCREMENT: an id is never reused after a purge deletes the newest row.
        {"sqlite_autoincrement": True},
    )

    id: Mapped[int] = mapped_column(_BIGINT_ID, primary_key=True, autoincrement=True)
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        sa.ForeignKey("conversations.id", ondelete="CASCADE")
    )
    role: Mapped[str] = mapped_column(sa.String(16))
    content: Mapped[str] = mapped_column(sa.Text)
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    expires_at: Mapped[datetime] = mapped_column(default=_expires_after_retention)

    conversation: Mapped[Conversation] = relationship(back_populates="messages")


class TurnRequest(Base):
    """A client's request to run one turn, kept so the same request is never
    run twice and so a crash in the middle can be recovered from.

    idempotency_key is chosen by the client and unique per conversation (and so
    per user, as a conversation has one owner). request_fingerprint is the
    SHA-256 hex digest of the request body: the same key with a different body
    is a conflict, not a replay.

    The request's input is its user message. A turn request is created together
    with the user Message it was made from, in one transaction (turns.py), and
    links it through user_message_id, which is NOT NULL: there is no turn request
    without recoverable input, in any status. The text is therefore stored once,
    in the history, and not again in the request; recovery reads it from the
    message (and may check it against request_fingerprint). The alternative, an
    immutable copy of the body inside the request, would duplicate the user's
    text for the length of the retention period for no gain.

    The links are database-enforced composite foreign keys:

      (conversation_id, user_message_id, user_message_role)
          -> messages (conversation_id, id, role)
      (conversation_id, assistant_message_id, assistant_message_role)
          -> messages (conversation_id, id, role)

    conversation_id is the request's own, so a message of another conversation
    (and therefore of another user) cannot be linked. The two *_role columns
    exist only to be part of those keys: each is pinned to a constant by a CHECK
    ('user' and 'assistant'), so a message of the wrong role cannot be linked,
    and a linked message cannot later change its conversation or its role. A
    message belongs to at most one request (UNIQUE on each id column). The
    assistant link is NULL until the reply is committed (a MATCH SIMPLE foreign
    key is not checked while any of its columns is NULL).

    The links are ON DELETE NO ACTION, so a message that a request points at
    cannot be deleted on its own: deleting it is refused, loudly, instead of
    leaving a request without its input or quietly dropping the request. The
    check is immediate (at the end of the statement), so a bad link is reported
    by the statement that makes it. Deleting a conversation or a user still
    removes everything beneath it in one go: the cascade deletes the messages and
    the requests before the check runs. (Verified on SQLite and on PostgreSQL 16,
    in both orders in which the two cascades can fire. Deferring the check was
    tried and dropped: it was not needed, and it reported violations only at
    COMMIT.)

    The status columns carry what a recovery needs: attempt_count, when the
    latest attempt started and when its lease runs out (a PROCESSING or
    COMMITTING row past its lease belongs to a worker that died). result_payload
    is the reply: absent until it has been generated, present from COMMITTING
    on, replayed as-is for a COMPLETED request, and kept by a FAILED request
    whose failure_kind is PERSISTENCE so that the commit can be retried without
    generating again. error_code is the free-form detail of a failure;
    failure_kind is the part a recovery branches on. The message ids say how
    far the commit got (a COMMITTING row with an assistant_message_id only
    needs its status moved on).

    Every scenario is one (status, failure_kind) pair, and the CHECKs keep the
    pair and the other columns consistent:

      accepted               pending
      running                processing
      reply being committed  committing  (the reconciliation state)
      reply committed        completed
      generation failed      failed, failure_kind=generation   (no reply)
      persistence failed     failed, failure_kind=persistence  (reply kept)
      cancelled              cancelled

    A failure to store the request itself leaves no row to describe it: the
    client got an error and retries with the same idempotency key.

    Retention: result_payload holds a copy of the answer, so the request
    expires at most RETENTION_DAYS after its own creation (a CHECK), never
    later than that, and in practice no later than the assistant message it
    copies. The purge job (a later increment) must delete expired *terminal*
    requests before it deletes messages, and must resolve (fail or cancel) an
    expired request that is still in flight rather than delete it: the database
    refuses to delete a message a request links, so a purge that forgets fails
    loudly and orphans nothing.

    Not built yet (R5, the turn-processing increment). Nothing here is relied on
    by the schema, and the tests that move a request between statuses through
    ORM attributes show only what the CHECKs allow, not that a transition is
    safe under concurrency. R5 must provide, and test with competing workers:

      * Lease chronology: created_at <= processing_started_at < lease_expires_at,
        finished_at >= processing_started_at, one clock for all of them (the
        application's UTC clock, never mixed with the database's), and a row is
        abandoned only when lease_expires_at is in the past by a grace margin.
        None of this is a CHECK today.
      * Atomic compare-and-swap transitions: every transition is one
        `UPDATE ... SET status = :next ... WHERE id = :id AND status = :expected
        [AND attempt_count = :attempt] [AND lease_expires_at < :now]` whose row
        count must be 1, never read-modify-write on an ORM object; attempt_count
        is the fencing token, so a worker that lost its lease cannot commit.
      * The assistant Message and the move to COMPLETED in one transaction, and
        a recovery that first compares sha256(user message text) with
        request_fingerprint.
      * Competing-worker tests: two connections claiming the same pending row
        (exactly one wins); a stale worker committing after its lease expired and
        another worker reclaimed the row (refused); a worker dying between the
        assistant message and the status change (reconciled, not duplicated);
        run against a file database with separate connections, and against
        PostgreSQL (SELECT ... FOR UPDATE SKIP LOCKED) before it is deployed.
    """

    __tablename__ = "turn_requests"
    __table_args__ = (
        sa.UniqueConstraint("conversation_id", "idempotency_key"),
        # A message is the input or the answer of at most one request.
        sa.UniqueConstraint("user_message_id"),
        sa.UniqueConstraint("assistant_message_id"),
        sa.Index(None, "status", "lease_expires_at"),
        sa.Index(None, "expires_at"),
        # Explicit names: the convention's would be 75 characters or more, past
        # PostgreSQL's 63.
        sa.ForeignKeyConstraint(
            ["conversation_id", "user_message_id", "user_message_role"],
            ["messages.conversation_id", "messages.id", "messages.role"],
            name="fk_turn_requests_user_message",
            ondelete="NO ACTION",
        ),
        sa.ForeignKeyConstraint(
            ["conversation_id", "assistant_message_id", "assistant_message_role"],
            ["messages.conversation_id", "messages.id", "messages.role"],
            name="fk_turn_requests_assistant_message",
            ondelete="NO ACTION",
        ),
        sa.CheckConstraint("user_message_role = 'user'", name="user_message_role_is_user"),
        sa.CheckConstraint(
            "assistant_message_role = 'assistant'", name="assistant_message_role_is_assistant"
        ),
        sa.CheckConstraint(
            f"length(idempotency_key) BETWEEN 1 AND {MAX_IDEMPOTENCY_KEY_LENGTH}",
            name="idempotency_key_length",
        ),
        sa.CheckConstraint(PrintableAscii("idempotency_key"), name="idempotency_key_printable_ascii"),
        sa.CheckConstraint("length(request_fingerprint) = 64", name="fingerprint_length"),
        _max_length("error_code", 64),
        sa.CheckConstraint(_in_list("status", TurnStatus), name="status_valid"),
        sa.CheckConstraint("attempt_count >= 0", name="attempt_count_non_negative"),
        sa.CheckConstraint(
            "status <> 'processing' OR "
            "(processing_started_at IS NOT NULL AND lease_expires_at IS NOT NULL)",
            name="processing_has_lease",
        ),
        sa.CheckConstraint(
            "status <> 'completed' OR (result_payload IS NOT NULL AND finished_at IS NOT NULL)",
            name="completed_has_result",
        ),
        sa.CheckConstraint(
            "status <> 'failed' OR (error_code IS NOT NULL AND finished_at IS NOT NULL)",
            name="failed_has_error",
        ),
        sa.CheckConstraint(
            "status <> 'committing' OR (result_payload IS NOT NULL AND "
            "processing_started_at IS NOT NULL AND lease_expires_at IS NOT NULL)",
            name="committing_has_reply_and_lease",
        ),
        sa.CheckConstraint(_in_list("failure_kind", FailureKind), name="failure_kind_valid"),
        sa.CheckConstraint(
            "(status = 'failed' AND failure_kind IS NOT NULL) OR "
            "(status <> 'failed' AND failure_kind IS NULL)",
            name="failure_kind_iff_failed",
        ),
        sa.CheckConstraint(
            "failure_kind <> 'generation' OR result_payload IS NULL",
            name="generation_failure_has_no_reply",
        ),
        sa.CheckConstraint(
            "failure_kind <> 'persistence' OR result_payload IS NOT NULL",
            name="persistence_failure_keeps_reply",
        ),
        sa.CheckConstraint(
            "status <> 'cancelled' OR finished_at IS NOT NULL", name="cancelled_has_finish"
        ),
        sa.CheckConstraint(
            "finished_at IS NULL OR status IN ('completed', 'failed', 'cancelled')",
            name="finished_only_when_terminal",
        ),
        sa.CheckConstraint("expires_at > created_at", name="expires_after_created"),
        sa.CheckConstraint(WithinRetention("created_at", "expires_at"), name="expires_within_retention"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    conversation_id: Mapped[uuid.UUID] = mapped_column(
        sa.ForeignKey("conversations.id", ondelete="CASCADE")
    )
    idempotency_key: Mapped[str] = mapped_column(sa.String(MAX_IDEMPOTENCY_KEY_LENGTH))
    request_fingerprint: Mapped[str] = mapped_column(sa.String(64))
    status: Mapped[str] = mapped_column(
        sa.String(16),
        default=TurnStatus.PENDING.value,
        server_default=TurnStatus.PENDING.value,
    )
    attempt_count: Mapped[int] = mapped_column(
        sa.Integer, default=0, server_default=sa.text("0")
    )
    created_at: Mapped[datetime] = mapped_column(default=utcnow)
    updated_at: Mapped[datetime] = mapped_column(default=utcnow, onupdate=utcnow)
    processing_started_at: Mapped[Optional[datetime]]
    lease_expires_at: Mapped[Optional[datetime]]
    finished_at: Mapped[Optional[datetime]]
    error_code: Mapped[Optional[str]] = mapped_column(sa.String(64))
    failure_kind: Mapped[Optional[str]] = mapped_column(sa.String(16))
    result_payload: Mapped[Optional[dict[str, Any]]] = mapped_column(_JSON_PAYLOAD)
    user_message_id: Mapped[int] = mapped_column(_BIGINT_ID)
    user_message_role: Mapped[str] = mapped_column(
        sa.String(16),
        default=MessageRole.USER.value,
        server_default=MessageRole.USER.value,
    )
    assistant_message_id: Mapped[Optional[int]] = mapped_column(_BIGINT_ID)
    assistant_message_role: Mapped[str] = mapped_column(
        sa.String(16),
        default=MessageRole.ASSISTANT.value,
        server_default=MessageRole.ASSISTANT.value,
    )
    expires_at: Mapped[datetime] = mapped_column(default=_expires_after_retention)

    conversation: Mapped[Conversation] = relationship(back_populates="turn_requests")
    # Read-only: the ids (and the foreign keys above) are the source of truth,
    # and a writable relationship would also try to write conversation_id, which
    # two other columns share.
    user_message: Mapped[Message] = relationship(
        primaryjoin="TurnRequest.user_message_id == Message.id",
        foreign_keys=[user_message_id],
        viewonly=True,
    )
