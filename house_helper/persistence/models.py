# --- the same rules, enforced before the INSERT on the ORM write path -------------
#
# The CHECKs above are what holds for any writer. These run first on rows written
# through the ORM, so a caller gets a ValueError that says what is wrong rather
# than a database error (and so a rule that the database cannot express, such as
# "created_at never changes", is still kept on this path). Core statements and
# raw SQL skip them and meet the CHECKs.


def check_retention(created_at: datetime, expires_at: datetime) -> None:
    """ValueError unless created_at < expires_at <= created_at + RETENTION."""
    if created_at.tzinfo is None or expires_at.tzinfo is None:
        return  # UtcDateTime refuses a naive timestamp, with its own message
    if expires_at <= created_at:
        raise ValueError("expires_at must be after created_at")
    if expires_at - created_at > MESSAGE_RETENTION:
        raise ValueError(f"expires_at may be at most {MESSAGE_RETENTION_DAYS} days after created_at")


def _changed(target: Any, *attributes: str) -> list[str]:
    state = sa.inspect(target)
    return [name for name in attributes if state.attrs[name].history.has_changes()]


def _forbid_changes(target: Any, *attributes: str) -> None:
    changed = _changed(target, *attributes)
    if changed:
        raise ValueError(f"{type(target).__name__}.{', '.join(changed)} cannot change once stored")


def _guard_retention_on_insert(mapper: Any, connection: Any, target: Any) -> None:
    if target.created_at is None:
        target.created_at = utcnow()
    if target.expires_at is None:
        target.expires_at = target.created_at + MESSAGE_RETENTION
    check_retention(target.created_at, target.expires_at)


def _guard_retention_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "created_at")
    if _changed(target, "expires_at"):
        check_retention(target.created_at, target.expires_at)


def _guard_message(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "conversation_id", "role")
    _guard_retention_on_update(mapper, connection, target)


def _guard_turn_request_on_insert(mapper: Any, connection: Any, target: Any) -> None:
    validate_idempotency_key(target.idempotency_key)
    _guard_retention_on_insert(mapper, connection, target)


def _guard_turn_request_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(
        target,
        "conversation_id",
        "idempotency_key",
        "request_fingerprint",
        "user_message_id",
    )
    _guard_retention_on_update(mapper, connection, target)


def _guard_identity(mapper: Any, connection: Any, target: Any) -> None:
    pair = (target.provider, target.subject)
    if None in pair:
        return  # NOT NULL is the database's to report
    if normalize_identity(*pair) != pair:
        raise ValueError(
            f"{type(target).__name__} {pair!r} is not in normalized form; "
            "use identifiers.normalize_identity"
        )


def _guard_session_on_update(mapper: Any, connection: Any, target: Any) -> None:
    _forbid_changes(target, "identity_link_id")


sa.event.listen(Session, "before_update", _guard_session_on_update)
sa.event.listen(Message, "before_insert", _guard_retention_on_insert)
sa.event.listen(Message, "before_update", _guard_message)
sa.event.listen(TurnRequest, "before_insert", _guard_turn_request_on_insert)
sa.event.listen(TurnRequest, "before_update", _guard_turn_request_on_update)
for _identity_model in (AllowlistEntry, IdentityLink):
    sa.event.listen(_identity_model, "before_insert", _guard_identity)
    sa.event.listen(_identity_model, "before_update", _guard_identity)
