class MessageRole(str, enum.Enum):
    """Roles kept in a conversation's history.

    USER and ASSISTANT are the conversation itself (what the chat core stores).
    SYSTEM_NOTE is a marker the application writes into the history, not
    something said to or by the model; the first use is the context reset: the
    context of a conversation is the messages after its latest system note. The
    name is deliberately not "system", so a note cannot be mistaken for, or
    forwarded as, a provider's system prompt.
    """

    USER = "user"
    ASSISTANT = "assistant"
    SYSTEM_NOTE = "system_note"


class AllowlistProvider(str, enum.Enum):
    """How a person on the allowlist is identified. The value is also the
    `provider` their IdentityLink carries once they have signed in."""

    TELEGRAM = "telegram"  # subject: the `sub` of Telegram's OIDC ID token (primary login)
    EMAIL = "email"  # subject: a verified address, normalized (backup login)


class TurnStatus(str, enum.Enum):
    """Where a turn request is in its life. The transitions are not enforced
    here (that is the turn-processing increment); the database only guarantees
    that a row in a given status carries what that status needs.

    Intended path: PENDING -> PROCESSING -> COMMITTING -> COMPLETED. The reply is
    generated while PROCESSING and written into result_payload on entering
    COMMITTING, so a crash after that point is finished from the stored reply
    and never generates a second one.
    """

    PENDING = "pending"  # accepted and stored, not yet picked up
    PROCESSING = "processing"  # claimed, reply being generated; holds a lease
    COMMITTING = "committing"  # reply generated and stored; being committed; holds a lease
    COMPLETED = "completed"  # reply committed; result_payload is the answer to replay
    FAILED = "failed"  # failure_kind and error_code say how
    CANCELLED = "cancelled"  # the request was withdrawn; nothing is replayed


class FailureKind(str, enum.Enum):
    """Why a FAILED turn failed. It decides how a retry may proceed."""

    GENERATION = "generation"  # no reply exists; a retry generates one
    PERSISTENCE = "persistence"  # the reply exists in result_payload; a retry only commits it


def _in_list(column: str, members: type[enum.Enum]) -> str:
    values = ", ".join(f"'{member.value}'" for member in members)
    return f"{column} IN ({values})"


def _max_length(column: str, limit: int) -> sa.CheckConstraint:
    """SQLite ignores the width in VARCHAR(n); this is what makes it a limit.
    A NULL passes (length(NULL) is NULL), so it suits nullable columns too."""
    return sa.CheckConstraint(f"length({column}) <= {limit}", name=f"{column}_max_length")


def _identity_checks() -> list[sa.CheckConstraint]:
    """The rules for a (provider, subject) pair, identical on allowlist_entries
    and identity_links so that the two tables cannot disagree about what an
    identity looks like. identifiers.normalize_identity is the application-side
    twin of these five."""
    return [
        sa.CheckConstraint(_in_list("provider", AllowlistProvider), name="provider_valid"),
        sa.CheckConstraint(
            f"length(subject) BETWEEN 1 AND {MAX_SUBJECT_LENGTH}", name="subject_length"
        ),
        sa.CheckConstraint(PrintableAscii("subject"), name="subject_printable_ascii"),
        # An email is stored lower-case with exactly one "@" and something on
        # both sides of it. (Lower-casing is ASCII-only on both databases, which
        # is all that subject_printable_ascii lets through.)
        sa.CheckConstraint(
            "provider <> 'email' OR (subject = lower(subject) "
            "AND length(subject) - length(replace(subject, '@', '')) = 1 "
            "AND substr(subject, 1, 1) <> '@' "
            "AND substr(subject, length(subject), 1) <> '@')",
            name="email_subject_normalized",
        ),
        # A Telegram subject can never be taken for an address or a @handle.
        sa.CheckConstraint(
            "provider <> 'telegram' OR replace(subject, '@', '') = subject",
            name="telegram_subject_not_email",
        ),
    ]


def _expires_after_retention(context: DefaultExecutionContext) -> datetime:
    """Default for expires_at: the row's own created_at plus the retention period.

    Reads created_at from the same insert (its default runs first because the
    column is declared first), so the pair is always exactly MESSAGE_RETENTION
    apart even when created_at is supplied by the caller.
    """
    return context.get_current_parameters()["created_at"] + MESSAGE_RETENTION


# JSON on SQLite, JSONB on PostgreSQL. none_as_null: a Python None is SQL NULL,
# not the JSON value null, so "is there a payload" is a plain IS NOT NULL.
_JSON_PAYLOAD = sa.JSON(none_as_null=True).with_variant(
    postgresql.JSONB(none_as_null=True), "postgresql"
)

# BIGINT on PostgreSQL; SQLite only auto-increments a column typed INTEGER.
_BIGINT_ID = sa.BigInteger().with_variant(sa.Integer(), "sqlite")


